//! ASCII text metrics for centred labels (standard Helvetica widths).
//!
//! The SVG and PDF writers share this table so text centres identically in
//! both, and the values are the published Helvetica (Type1 base-14) widths in
//! 1/1000 em — not guessed. Characters outside the table default to 556 (the
//! digit width), which is only reached for punctuation we never emit in a
//! drawing label ("?") — a safety net, never silently clipped.

