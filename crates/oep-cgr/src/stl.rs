//! STL export for the internal tessellation mesh (P2-M2-T02).
//!
//! Writes a binary or ASCII STL from an indexed triangle mesh
//! (`positions: &[[f32; 3]]` + `triangles: &[[u32; 3]]`). The coordinates
//! are the internal mesh representation named by P2-M2-T01
//! (vertices / indices / triangles); P2-M2-T03 adds glTF on the same input.
//!
//! ## Format contract
//!
//! **Binary STL** (the de-facto standard; small, exact, what CAD side-loads
//! expect):
//!   * 80-byte header, zero-filled;
//!   * `u32` little-endian triangle count;
//!   * per triangle (50 bytes): facet normal `3 x f32`, the 3 vertices
//!     `9 x f32`, `u16` attribute byte count (0).
//!
//! The facet normal is the right-hand-rule unit normal
//! `normalize(cross(v1 - v0, v2 - v0))`. Consumers MUST NOT trust STL
//! normals anyway (the format spec says readers recompute); we still write
//! them for interchange hygiene.
//!
//! **ASCII STL** (legacy/human-readable): `solid <name>` … `endsolid <name>`
//! with one `facet`/`outer loop`/`endloop`/`endfacet` block per triangle.
//!
//! ## Golden-file discipline
//!
//! The committed reference
//! `tests/golden/box-reference.bin.stl` is generated by
//! `tools/gen_golden_box.py` — an INDEPENDENT encoder written from the spec,
//! NOT by this writer — so `tests/golden_stl.rs` proves byte-for-byte
//! conformance against a reference tessellation (`corpus/data/box.stl`,
//! CC0-1.0 P0-M4-T02 fixture).
//!
//! Errors are typed and never panic: triangle indices are bounds-checked
//! before writing (`StlError::IndexOutOfRange`), degenerate zero-area
//! triangles are rejected (`StlError::DegenerateTriangle`), and IO failures
//! surface as `StlError::Io`.

use std::fmt;
use std::io::Write;

/// A triangle with zero area under the right-hand rule (duplicate or
/// co-linear vertices) — would produce a meaningless facet.
const DEGENERATE_EPS: f32 = 1e-12;

/// Errors produced during STL export.
#[derive(Debug)]
pub enum StlError {
    /// A triangle index referenced a vertex position that does not exist.
    IndexOutOfRange {
        /// The offending index.
        index: u32,
        /// The number of positions in the mesh.
        len: usize,
    },
    /// A triangle is degenerate (zero area) and cannot be exported as a facet.
    DegenerateTriangle,
    /// Underlying IO failure while writing.
    Io(std::io::Error),
}

impl fmt::Display for StlError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            StlError::IndexOutOfRange { index, len } => {
                write!(f, "triangle index {index} out of range (positions: {len})")
            }
            StlError::DegenerateTriangle => write!(f, "degenerate triangle (zero area)"),
            StlError::Io(e) => write!(f, "io error: {e}"),
        }
    }
}

impl std::error::Error for StlError {}

impl From<std::io::Error> for StlError {
    fn from(e: std::io::Error) -> Self {
        StlError::Io(e)
    }
}

/// Cross product `u x v` as an f32 triple.
fn cross(u: [f32; 3], v: [f32; 3]) -> [f32; 3] {
    [
        u[1] * v[2] - u[2] * v[1],
        u[2] * v[0] - u[0] * v[2],
        u[0] * v[1] - u[1] * v[0],
    ]
}

/// Right-hand-rule unit normal of a triangle. Returns `None` for a
/// zero-area (degenerate) triangle.
fn facet_normal(p0: [f32; 3], p1: [f32; 3], p2: [f32; 3]) -> Option<[f32; 3]> {
    let u = [p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]];
    let v = [p2[0] - p0[0], p2[1] - p0[1], p2[2] - p0[2]];
    let n = cross(u, v);
    let mag = (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]).sqrt();
    if mag <= DEGENERATE_EPS {
        return None;
    }
    Some([n[0] / mag, n[1] / mag, n[2] / mag])
}

/// Resolve a triangle's three positions, bounds-checked.
fn triangle_positions(positions: &[[f32; 3]], tri: &[u32; 3]) -> Result<[[f32; 3]; 3], StlError> {
    let mut out = [[0.0f32; 3]; 3];
    for (k, &idx) in tri.iter().enumerate() {
        let i = idx as usize;
        if i >= positions.len() {
            return Err(StlError::IndexOutOfRange {
                index: idx,
                len: positions.len(),
            });
        }
        out[k] = positions[i];
    }
    Ok(out)
}

/// Write the mesh as **binary** STL into `w`.
///
/// Layout: 80-byte zero header, `u32` LE triangle count, then 50 bytes per
/// triangle (normal, 3 vertices, u16 attr). Byte-for-byte stable for a given
/// mesh (little-endian always, exact f32), which is what the golden-file test
/// locks to.
pub fn write_binary_stl<W: Write>(
    positions: &[[f32; 3]],
    triangles: &[[u32; 3]],
    w: &mut W,
) -> Result<(), StlError> {
    let mut out = Vec::with_capacity(84 + 50 * triangles.len());
    out.resize(80, 0u8); // header
    out.extend_from_slice(&(triangles.len() as u32).to_le_bytes());
    for tri in triangles {
        let pts = triangle_positions(positions, tri)?;
        let normal = facet_normal(pts[0], pts[1], pts[2]).ok_or(StlError::DegenerateTriangle)?;
        for c in normal {
            out.extend_from_slice(&c.to_le_bytes());
        }
        for p in pts {
            for c in p {
                out.extend_from_slice(&c.to_le_bytes());
            }
        }
        out.extend_from_slice(&0u16.to_le_bytes()); // attribute byte count
    }
    w.write_all(&out)?;
    Ok(())
}

/// Write the mesh as **ASCII** STL into `w` (legacy `solid` syntax).
///
/// Numbers are printed in shortest round-trip form (`{}` on `f32`), so any
/// exact coordinate round-trips; byte-identical for a given mesh.
pub fn write_ascii_stl<W: Write>(
    positions: &[[f32; 3]],
    triangles: &[[u32; 3]],
    w: &mut W,
) -> Result<(), StlError> {
    w.write_all(b"solid oep-cgr mesh\n")?;
    for tri in triangles {
        let pts = triangle_positions(positions, tri)?;
        let normal = facet_normal(pts[0], pts[1], pts[2]).ok_or(StlError::DegenerateTriangle)?;
        writeln!(
            w,
            "  facet normal {} {} {}\n    outer loop",
            normal[0], normal[1], normal[2]
        )?;
        for p in pts {
            writeln!(w, "      vertex {} {} {}", p[0], p[1], p[2])?;
        }
        writeln!(w, "    endloop\n  endfacet")?;
    }
    w.write_all(b"endsolid oep-cgr mesh\n")?;
    Ok(())
}
