//! Deterministic, self-contained hash helpers for the farm crate.
//!
//! No external crypto dependency (std-only doctrine): the integrity of a
//! checkpoint and the byte-equivalence guarantee only need a *deterministic*
//! digest that is stable across hosts and runs. FNV-1a 64 is exactly that:
//! pure integer arithmetic, identical on every platform, collision-resistant
//! enough to catch any byte difference in the artifact prefix (which is the
//! property resume needs). SplitMix64 is the deterministic PRNG used to
//! fabricate reproducible work-item bytes.

/// The FNV-1a 64-bit offset basis.
pub const FNV1A64_OFFSET_BASIS: u64 = 0xcbf2_9ce4_8422_2325;
/// The FNV-1a 64-bit prime.
pub const FNV1A64_PRIME: u64 = 0x0000_0100_0000_01b3;

/// Compute the FNV-1a 64-bit hash of `data`.
pub fn fnv1a64(data: &[u8]) -> u64 {
    let mut hasher = Fnv1a64::new();
    hasher.update(data);
    hasher.finish()
}

/// Incremental FNV-1a 64-bit hasher (byte-wise fold, no allocation).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Fnv1a64 {
    state: u64,
}

impl Fnv1a64 {
    /// A fresh hasher at the standard offset basis.
    pub fn new() -> Self {
        Fnv1a64 {
            state: FNV1A64_OFFSET_BASIS,
        }
    }

    /// Absorb `data` into the running fold.
    pub fn update(&mut self, data: &[u8]) {
        for &b in data {
            self.state ^= u64::from(b);
            self.state = self.state.wrapping_mul(FNV1A64_PRIME);
        }
    }

    /// The current 64-bit digest.
    pub fn finish(&self) -> u64 {
        self.state
    }
}

/// SplitMix64: a fast, deterministic 64-bit PRNG (Wang Yi, public domain).
///
/// Pure integer arithmetic, so the generated byte stream is identical on
/// every host. Used to derive reproducible work-item bytes from a job seed.
#[must_use]
pub fn splitmix64(z: u64) -> u64 {
    let mut z = z.wrapping_add(0x9e37_79b9_7f4a_7c15);
    z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    z ^ (z >> 31)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fnv1a64_known_vectors() {
        // Reference vectors (empty + classic FNV-1a 64 examples).
        assert_eq!(fnv1a64(b""), 0xcbf2_9ce4_8422_2325);
        assert_eq!(fnv1a64(b"a"), 0xaf63_dc4c_8601_ec8c);
        assert_eq!(fnv1a64(b"foobar"), 0x8594_4171_f739_67e8);
        // Incremental == one-shot.
        let mut h = Fnv1a64::new();
        h.update(b"foo");
        h.update(b"bar");
        assert_eq!(h.finish(), fnv1a64(b"foobar"));
    }

    #[test]
    fn splitmix64_is_deterministic_and_scrambled() {
        let a = splitmix64(1);
        let b = splitmix64(1);
        assert_eq!(a, b, "same input, same output, on every host");
        assert_ne!(splitmix64(1), splitmix64(2));
        // Well-known first output for state 0 documented in the reference impl.
        assert_eq!(splitmix64(0), 0xe220_a839_7b1d_cdaf);
    }
}
