//! P6-M4-T01 -- Exporters of the P6 geometry core.
//!
//! Every exporter consumes the canonical internal mesh representation as
//! plain slices (`positions: &[[f32; 3]]` + `triangles: &[[u32; 3]]`, the
//! vertices/indices/triangles representation named by P2-M2-T01) so it is
//! independent of the concrete `Mesh` type and trivially callable with
//! `mesh.vertices()` / `mesh.triangles()` once the geometry kernel lands.
//!
//! The reference tessellation for the golden tests is the keelworks CC0-1.0
//! unit box (8 corners / 12 triangles, `corpus/data/box.stl` fixture); every
//! format's golden file is generated by an INDEPENDENT encoder in
//! `crates/oep-geo/tools/` from the format spec (not by these writers), and
//! the Python acceptance test (`tests/test_oep_geo_exporters_acceptance.py`)
//! re-parses those goldens with pure-stdlib decoders.
//!
//! Formats covered:
//!
//! * [`stl`] -- binary + ASCII STL.
//! * [`gltf`] -- glTF 2.0: binary GLB container and `.gltf`+`.bin` pair.
//! * [`obj`] -- Wavefront OBJ (vertices + faces).
//! * [`svg`] -- 2D vector drawing (orthographic XY projection of the mesh's
//!   unique edges) as an SVG document (projected-edge drawing).
//! * [`pdf`] -- the same 2D drawing path as a minimal, valid PDF document
//!   (PDF drawing path).
//! * [`step`] -- STEP / ISO 10303-21 faceted B-Rep passthrough, honestly
//!   marked as tessellated (NOT claimed as exact analytic B-Rep); the STEP
//!   export lane is owned by P4 (see [`step`] module docs).
//!
//! All writers are dependency-free, deterministic (byte-for-byte for a given
//! mesh + options), typed-error (never panic), and follow the tolerant
//! failure / honest-marking conventions established by the P2/P3 exporters.
//!
//! ## Shared error type
//!
//! The variants overlap across formats, so one [`ExportError`] is shared and
//! each format module aliases it under its familiar name (`StlError`,
//! `GltfError`, `ObjError`, `SvgError`, `PdfError`, `StepError`).

#![deny(missing_docs)]

mod base;

pub mod gltf;
pub mod obj;
pub mod pdf;
pub mod step;
pub mod stl;
pub mod svg;

pub use base::ExportError;

/// STL export error (alias of the shared [`ExportError`]).
pub type StlError = ExportError;
/// glTF export error (alias of the shared [`ExportError`]).
pub type GltfError = ExportError;
/// Wavefront OBJ export error (alias of the shared [`ExportError`]).
pub type ObjError = ExportError;
/// SVG export error (alias of the shared [`ExportError`]).
pub type SvgError = ExportError;
/// PDF export error (alias of the shared [`ExportError`]).
pub type PdfError = ExportError;

pub use gltf::{write_glb, write_gltf_bin, write_gltf_json};
pub use obj::write_obj;
pub use pdf::write_pdf_drawing;
pub use step::{write_step, StepOpts, StepStats};
pub use stl::{write_ascii_stl, write_binary_stl};
pub use svg::write_svg_2d;
