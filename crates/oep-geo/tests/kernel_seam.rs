// ---------------------------------------------------------------------------
// Fillet / chamfer of one box-reference edge (radius/distance 0.2), asserting
// volume + face count against both the closed form and the golden.
// ---------------------------------------------------------------------------

#[test]
fn fillet_box_edge_matches_analytic_and_golden() {
    let golden = load_golden();
    let sys = sys_new().expect("session");
    let boxed = box_reference(&sys);
    let edges = solid_edges(&sys, &boxed, tol()).expect("edges");
    // OCCT reports each edge once per incident-face occurrence (a cube yields
    // 24 edge rows, 12 unique); that per-occurrence count is the kernel answer.
    assert_eq!(edges.len(), 24, "OCCT box edge occurrences");

    // A radius-0.2 fillet on one straight edge of the unit cube removes a
    // quarter-cylinder of material: 1 * (r^2 - pi*r^2/4) over unit length.
    let removed = 1.0 * (0.2 * 0.2 - PI * 0.2 * 0.2 / 4.0);
    let f = solid_fillet(&sys, &[edges[0]], 0.2, tol()).expect("fillet");
    assert_analytic_volume(f.measures.volume, 1.0 - removed, "fillet r0.2 box edge");
    assert_matches_golden("fillet", &f.measures, golden["fillet"]);
    sys_drop(&sys);
}

#[test]
fn chamfer_box_edge_matches_analytic_and_golden() {
    let golden = load_golden();
    let sys = sys_new().expect("session");
    let boxed = box_reference(&sys);
    let edges = solid_edges(&sys, &boxed, tol()).expect("edges");

    // A symmetric distance-0.2 chamfer on one straight edge of the unit cube
    // removes a right prism of cross-section d^2/2 over unit length.
    let removed = 1.0 * (0.2 * 0.2 / 2.0);
    let c = solid_chamfer(&sys, &[edges[0]], 0.2, tol()).expect("chamfer");
    assert_analytic_volume(c.measures.volume, 1.0 - removed, "chamfer d0.2 box edge");
    assert_matches_golden("chamfer", &c.measures, golden["chamfer"]);
    sys_drop(&sys);
}

// ---------------------------------------------------------------------------
// Sweeps: extrude of the box-reference footprint, revolve of a meridian
// derived from the same footprint (full turn annulus).
// ---------------------------------------------------------------------------

#[test]
fn extrude_profile_matches_analytic_and_golden() {
    let golden = load_golden();
    let sys = sys_new().expect("session");
    // Same footprint as the box-reference solid (the unit square), swept by 1:
    // the extruded solid IS a unit box, volume exactly 1.
    let square = [
        Point2D::new(0.0, 0.0),
        Point2D::new(1.0, 0.0),
        Point2D::new(1.0, 1.0),
        Point2D::new(0.0, 1.0),
    ];
    let ex = solid_extrude(&sys, &square, 1.0, tol()).expect("extrude");
    assert_analytic_volume(ex.measures.volume, 1.0, "extruded unit square");
    assert_matches_golden("extrude", &ex.measures, golden["extrude"]);
    sys_drop(&sys);
}

#[test]
fn revolve_meridian_matches_analytic_and_golden() {
    let golden = load_golden();
    let sys = sys_new().expect("session");
    // Meridian cross-section (r in [0.4, 1.0], height 1.0) revolved a full
    // turn about Z: a hollow-cylinder annulus of volume pi*(1^2 - 0.4^2)*1.
    let meridian = [
        Point2D::new(0.4, 0.0),
        Point2D::new(1.0, 0.0),
        Point2D::new(1.0, 1.0),
        Point2D::new(0.4, 1.0),
    ];
    let rv = solid_revolve(&sys, &meridian, 2.0 * PI, tol()).expect("revolve");
    let annulus = PI * (1.0 - 0.4 * 0.4) * 1.0;
    assert_analytic_volume(rv.measures.volume, annulus, "revolved annulus (full turn)");
    assert_matches_golden("revolve", &rv.measures, golden["revolve"]);
    sys_drop(&sys);
}

