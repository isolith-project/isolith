#[test]
fn rep_markup_is_deterministic() {
    let (pos, tri) = box_mesh();
    let a = rep_bytes(&pos, &tri);
    let b = rep_bytes(&pos, &tri);
    assert_eq!(a, b, "same mesh must byte-identically encode");
}

#[test]
fn rep_markup_has_declaration_and_observed_spine() {
    let (pos, tri) = box_mesh();
    let xml = String::from_utf8(rep_bytes(&pos, &tri)).expect("UTF-8 rep");
    assert!(
        xml.starts_with("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"),
        "XML declaration first line"
    );
    assert!(xml.contains("<XMLRepresentation version=\"1.0\""));
    assert!(xml.contains("xmlns=\"http://www.3ds.com/xsd/3DXML\""));
    assert!(xml.contains("<Root xsi:type=\"BagRepType\">"));
    assert!(xml.contains("<Rep xsi:type=\"PolygonalRepType\">"));
    assert!(xml.contains("<VertexBuffer><Positions>"));
    assert!(xml.contains("<Faces><Face strips=\""));
    assert!(xml.ends_with("</XMLRepresentation>\n"));
    // File must end as the last XML element (the observed ASCII-branch tail).
    assert!(xml.trim_end().ends_with('>'));
}

#[test]
fn rep_positions_preserved_exactly() {
    let (pos, tri) = box_mesh();
    let xml = String::from_utf8(rep_bytes(&pos, &tri)).unwrap();
    let text = extract_positions_text(&xml);
    let coords: Vec<[f32; 3]> = text
        .split(',')
        .map(|triple| {
            let mut it = triple.split_whitespace();
            [
                it.next().unwrap().parse::<f32>().unwrap(),
                it.next().unwrap().parse::<f32>().unwrap(),
                it.next().unwrap().parse::<f32>().unwrap(),
            ]
        })
        .collect();
    assert_eq!(coords.len(), pos.len());
    for (got, want) in coords.iter().zip(pos.iter()) {
        assert_eq!(got, want, "vertex coordinate must round-trip exactly");
    }
}

#[test]
fn rep_strips_decode_to_input_triangles() {
    let (pos, tri) = box_mesh();
    let xml = String::from_utf8(rep_bytes(&pos, &tri)).unwrap();
    let strips = extract_strips_text(&xml);
    let decoded: Vec<[u32; 3]> = strips
        .split(',')
        .map(|run| {
            let v: Vec<u32> = run.split_whitespace().map(|i| i.parse().unwrap()).collect();
            assert_eq!(v.len(), 3, "one 3-index strip-run per triangle");
            [v[0], v[1], v[2]]
        })
        .collect();
    assert_eq!(decoded, tri, "triangle indices must round-trip exactly");
}

