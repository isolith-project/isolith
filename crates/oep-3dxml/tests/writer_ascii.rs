//! P3-M4-T01 acceptance test (TDD, RED first) — writer: internal mesh -> 3DXML
//! ASCII (tessellated `.3DRep` markup + full ZIP package).
//!
//! Written BEFORE the `oep_3dxml::ascii` module existed (RED: this file does
//! not compile — there is no `oep_3dxml::ascii`). The contract, once GREEN:
//!
//! 1. `write_rep_markup(positions, triangles, opts, w)` emits the
//!    tessellated-ASCII `.3DRep` branch of 3DXML as well-formed XML:
//!    `<?xml ... ?>`, `<XMLRepresentation version="1.0"
//!    xmlns="http://www.3ds.com/xsd/3DXML" ...>`, `<Root
//!    xsi:type="BagRepType">` -> `<Rep xsi:type="PolygonalRepType">` ->
//!    `<Faces><Face strips="..."/>` -> `<VertexBuffer><Positions>...`
//!    (observed format facts, docs/re-notes/3dxml-hex-notebook.md §4.2).
//!    Positions are comma-separated "x y z" triples; face `strips` are
//!    comma-separated runs of space-separated vertex indices, ONE 3-index run
//!    per triangle (a 3-index strip decodes to exactly one triangle).
//! 2. Geometry is preserved EXACTLY and losslessly: parsing the emitted
//!    `<Positions>` and `<Face strips>` text back yields precisely the input
//!    mesh (same vertices, same triangles). No normals are emitted (the
//!    source triangle mesh carries none — we do not invent data).
//! 3. `write_package(positions, triangles, opts, w)` wraps the rep into a
//!    valid ZIP-archive 3DXML with exactly three STORED members —
//!    `Manifest.xml` (its `<Root>` names the model doc), `<name>.3dxml`
//!    (Header + ProductStructure + `ReferenceRep format="TESSELLATED"`
//!    `associatedFile="urn:3DXML:<name>.3DRep"`), and `<name>.3DRep` (the
//!    ASCII rep from 1). The ZIP parses via a correct central-directory walk
//!    and every member's exact bytes are recoverable.
//! 4. Deterministic: same input + options => byte-identical output; the
//!    package is byte-identical to a COMMITTED golden generated by an
//!    INDEPENDENT encoder (`tools/gen_golden_box_3dxml.py`, written in
//!    Python straight from the format facts — not by this writer).
//! 5. Typed errors, never panic: `EmptyMesh` (no positions or no triangles),
//!    `IndexOutOfRange` (triangle index >= vertex count), `NonFiniteVertex`,
//!    `DegenerateTriangle` (zero-area), `Io`. Validation runs BEFORE any
//!    bytes are written, so a failed call emits nothing.
//!
//! License compliance: the format here is written ONLY from observed facts of
//! public MIT/Apache-2.0 sample files (hex notebook) plus the internal-use
//! licensed 3DXML spec held privately (P1-M1-T02) — no Dassault XSD text is
//! reproduced anywhere in this output or test. This is our own data in a
//! conformant interchange shell, for internal use.
use std::panic::{catch_unwind, AssertUnwindSafe};

use oep_3dxml::ascii::{write_package, write_rep_markup, WriteError, WriterOpts};

/// The keelworks CC0-1.0 reference tessellation: the 8-corner unit box (same
/// order as `corpus/data/box.stl`, P0-M4-T02 fixture — 0/1 coordinates are
/// exact in f32, so equality checks are strong).
fn box_mesh() -> (Vec<[f32; 3]>, Vec<[u32; 3]>) {
    let positions = vec![
        [1.0, 0.0, 0.0], // V0
        [0.0, 1.0, 0.0], // V1
        [0.0, 0.0, 0.0], // V2
        [1.0, 1.0, 0.0], // V3
        [0.0, 0.0, 1.0], // V4
        [0.0, 1.0, 1.0], // V5
        [1.0, 0.0, 1.0], // V6
        [1.0, 1.0, 1.0], // V7
    ];
    let triangles = vec![
        [0, 1, 2],
        [0, 3, 1],
        [4, 5, 6],
        [5, 7, 6],
        [2, 6, 4],
        [2, 0, 6],
        [3, 5, 7],
        [3, 1, 5],
        [5, 1, 2],
        [5, 2, 4],
        [0, 7, 3],
        [0, 6, 7],
    ];
    (positions, triangles)
}

fn opts() -> WriterOpts<'static> {
    WriterOpts {
        product_name: "box",
        author: "keelworks",
        timestamp: "",
    }
}

fn rep_bytes(positions: &[[f32; 3]], triangles: &[[u32; 3]]) -> Vec<u8> {
    let mut buf = Vec::new();
    write_rep_markup(positions, triangles, &opts(), &mut buf).expect("rep write ok");
    buf
}

fn package_bytes(positions: &[[f32; 3]], triangles: &[[u32; 3]]) -> Vec<u8> {
    let mut buf = Vec::new();
    write_package(positions, triangles, &opts(), &mut buf).expect("package write ok");
    buf
}

/// Parse the `<Positions>` text block out of the rep markup.
fn extract_positions_text(xml: &str) -> String {
    let start = xml.find("<Positions>").expect("Positions open tag");
    let end = xml.find("</Positions>").expect("Positions close tag");
    xml[start + "<Positions>".len()..end].to_string()
}

/// Parse the `strips` attribute out of the `<Face ...>` element.
fn extract_strips_text(xml: &str) -> String {
    let start = xml.find("strips=\"").expect("strips attr") + "strips=\"".len();
    let end = xml[start..].find('"').expect("closing quote") + start;
    xml[start..end].to_string()
}

