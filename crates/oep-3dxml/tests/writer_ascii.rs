/// Walk the ZIP central directory and return (name, local-offset, csize,
/// usize) for every member. A correct, writer-independent ZIP parse.
fn central_entries(pkg: &[u8]) -> Vec<(String, u32, u32, u32)> {
    let mut eocd = None;
    for i in (0..=pkg.len().saturating_sub(22)).rev() {
        if pkg[i..i + 4] == [0x50, 0x4b, 0x05, 0x06] {
            eocd = Some(i);
            break;
        }
    }
    let eocd = eocd.expect("end-of-central-directory signature found");
    let cd_size = u32::from_le_bytes(pkg[eocd + 12..eocd + 16].try_into().unwrap());
    let cd_off = u32::from_le_bytes(pkg[eocd + 16..eocd + 20].try_into().unwrap());
    let mut entries = Vec::new();
    let mut p = cd_off as usize;
    let end = cd_off as usize + cd_size as usize;
    while p < end {
        assert_eq!(
            &pkg[p..p + 4],
            &[0x50, 0x4b, 0x01, 0x02],
            "central directory signature"
        );
        let name_len = u16::from_le_bytes(pkg[p + 28..p + 30].try_into().unwrap()) as usize;
        let extra_len = u16::from_le_bytes(pkg[p + 30..p + 32].try_into().unwrap()) as usize;
        let comment_len = u16::from_le_bytes(pkg[p + 32..p + 34].try_into().unwrap()) as usize;
        let csize = u32::from_le_bytes(pkg[p + 20..p + 24].try_into().unwrap());
        let usize_ = u32::from_le_bytes(pkg[p + 24..p + 28].try_into().unwrap());
        let offset = u32::from_le_bytes(pkg[p + 42..p + 46].try_into().unwrap());
        let name = String::from_utf8(pkg[p + 46..p + 46 + name_len].to_vec()).unwrap();
        entries.push((name, offset, csize, usize_));
        p += 46 + name_len + extra_len + comment_len;
    }
    entries
}

/// Slice out one STORED member's data bytes via the central directory.
fn zip_member<'a>(pkg: &'a [u8], name: &str) -> &'a [u8] {
    let name_bytes = name.len();
    let (_, off, csize, usize_) = central_entries(pkg)
        .into_iter()
        .find(|(n, _, _, _)| n == name)
        .unwrap_or_else(|| panic!("member {name} present in zip"));
    assert_eq!(csize, usize_, "STORED member: compressed == uncompressed");
    let data_off = off as usize + 30 + name_bytes;
    &pkg[data_off..data_off + usize_ as usize]
}

#[test]
fn package_is_a_valid_zip_with_three_members() {
    let (pos, tri) = box_mesh();
    let pkg = package_bytes(&pos, &tri);
    assert!(
        pkg.starts_with(&[0x50, 0x4b, 0x03, 0x04]),
        "PK\\x03\\x04 ZIP local-file header magic"
    );
    let entries = central_entries(&pkg);
    let names: Vec<&str> = entries.iter().map(|(n, _, _, _)| n.as_str()).collect();
    assert_eq!(
        names,
        vec!["Manifest.xml", "box.3dxml", "box.3DRep"],
        "exactly three members, ordered, observed ZIP-archive roles"
    );
}

#[test]
fn package_member_bytes_match_markup() {
    let (pos, tri) = box_mesh();
    let pkg = package_bytes(&pos, &tri);
    let manifest = std::str::from_utf8(zip_member(&pkg, "Manifest.xml")).unwrap();
    let model = std::str::from_utf8(zip_member(&pkg, "box.3dxml")).unwrap();
    let rep = std::str::from_utf8(zip_member(&pkg, "box.3DRep")).unwrap();

    // The rep member is byte-identical to the standalone rep writer.
    let expected_rep = rep_bytes(&pos, &tri);
    assert_eq!(
        rep.as_bytes(),
        &expected_rep[..],
        "rep member == rep writer"
    );

    // Manifest names the model doc.
    assert!(
        manifest.contains("box.3dxml"),
        "Manifest <Root> -> model doc"
    );

    // Model doc wires the rep via urn:3DXML: with the TESSELLATED format.
    assert!(model.contains("<Model_3dxml "));
    assert!(model.contains("<SchemaVersion>4.0</SchemaVersion>"));
    assert!(model.contains("<ProductStructure root=\"1\">"));
    assert!(model.contains("<Reference3D "));
    assert!(model.contains("<Instance3D "));
    assert!(
        model.contains(
            "<ReferenceRep id=\"21\" name=\"box\" format=\"TESSELLATED\" version=\"1.0\" associatedFile=\"urn:3DXML:box.3DRep\"/>"
        ),
        "TESSELLATED rep wiring + associatedFile URN"
    );
}

#[test]
fn package_matches_committed_independent_golden() {
    let (pos, tri) = box_mesh();
    let pkg = package_bytes(&pos, &tri);
    let golden_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("golden")
        .join("box-reference.3dxml");
    let golden = std::fs::read(&golden_path)
        .unwrap_or_else(|e| panic!("missing golden file {}: {e}", golden_path.display()));
    assert_eq!(
        pkg.len(),
        golden.len(),
        "package size must equal the independent golden"
    );
    assert_eq!(
        pkg, golden,
        "package bytes must equal the independent golden"
    );
}

