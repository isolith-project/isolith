// oep-engine-occ C++ glue implementation.
//
// The single translation unit that includes OCCT headers and the only place
// OCCT identifiers may appear in this crate's compiled code (ADR v1.1.0 "seam
// denial" -- the Rust side and oep-geo never name these). Mapped operations:
//
//   occMakeBox / occMakeCylinder / occMakeSphere -> BRepPrimAPI_*
//   occBoolean (0 union, 1 difference, 2 common)  -> BRepAlgoAPI_Fuse/Cut/Common
//   occFilletChamfer (0 fillet, 1 chamfer)        -> BRepFilletAPI_Make{Fillet,Chamfer}
//   occInfo / occEdges                            -> BRepGProp + TopExp_Explorer
//
// All functions report failure through OpOut/InfoOut/EdgesOut (ok=false +
// stable code + message); nothing unwinds over the FFI boundary.

