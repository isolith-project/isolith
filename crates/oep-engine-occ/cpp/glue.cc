namespace {

// --- session registry (owned here, guarded by a mutex) ----------------------

std::mutex g_mutex;
std::map<uint64_t, std::shared_ptr<OepSession>> g_sessions;
std::atomic<uint64_t> g_next_session(1);

std::shared_ptr<OepSession> sessionFor(uint64_t id) {
  std::lock_guard<std::mutex> lock(g_mutex);
  std::map<uint64_t, std::shared_ptr<OepSession>>::const_iterator it =
      g_sessions.find(id);
  if (it == g_sessions.end()) {
    return std::shared_ptr<OepSession>();
  }
  return it->second;
}

// --- status helpers ----------------------------------------------------------

OpOut fail(int32_t code, uint64_t token, const std::string& msg) {
  OpOut out;
  out.ok = false;
  out.code = code;
  out.token = token;
  out.message = rust::String(msg);
  return out;
}

OpOut okToken(uint64_t token) {
  OpOut out;
  out.ok = true;
  out.code = 0;
  out.token = token;
  out.message = rust::String();
  return out;
}

uint64_t countType(const TopoDS_Shape& shape, TopAbs_ShapeEnum kind) {
  uint64_t n = 0;
  for (TopExp_Explorer exp(shape, kind); exp.More(); exp.Next()) {
    ++n;
  }
  return n;
}

bool isEmptyOfFaces(const TopoDS_Shape& shape) {
  return shape.IsNull() || countType(shape, TopAbs_FACE) == 0;
}

bool edgeByIndex(const TopoDS_Shape& shape, uint64_t index, TopoDS_Edge& out) {
  if (shape.IsNull()) {
    return false;
  }
  uint64_t i = 0;
  for (TopExp_Explorer exp(shape, TopAbs_EDGE); exp.More(); exp.Next(), ++i) {
    if (i == index) {
      out = TopoDS::Edge(exp.Current());
      return true;
    }
  }
  return false;
}

}  // namespace

class OepSession {
 public:
  uint64_t add(const TopoDS_Shape& shape) {
    uint64_t token = next_;
    ++next_;
    shapes_[token] = shape;
    return token;
  }

  bool get(uint64_t token, TopoDS_Shape& out) const {
    std::map<uint64_t, TopoDS_Shape>::const_iterator it = shapes_.find(token);
    if (it == shapes_.end()) {
      return false;
    }
    out = it->second;
    return true;
  }

  uint64_t count() const { return static_cast<uint64_t>(shapes_.size()); }

 private:
  std::map<uint64_t, TopoDS_Shape> shapes_;
  uint64_t next_ = 1;
};

// --- session lifecycle --------------------------------------------------------

uint64_t occNewSession() {
  std::shared_ptr<OepSession> s = std::make_shared<OepSession>();
  uint64_t id;
  {
    std::lock_guard<std::mutex> lock(g_mutex);
    id = g_next_session.fetch_add(1);
    g_sessions[id] = s;
  }
  return id;
}

void occDropSession(uint64_t s) {
  std::lock_guard<std::mutex> lock(g_mutex);
  g_sessions.erase(s);
}

// --- primitives ------------------------------------------------------------------

OpOut occMakeBox(uint64_t s, double x0, double y0, double z0, double x1, double y1,
                 double z1, double /*tol*/) {
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    return fail(5, 0, "invalid session id");
  }
  if (!(x1 - x0 > 0.0 && y1 - y0 > 0.0 && z1 - z0 > 0.0)) {
    return fail(3, 0, "box has a non-positive size");
  }
  BRepPrimAPI_MakeBox mk(gp_Pnt(x0, y0, z0), gp_Pnt(x1, y1, z1));
  mk.Build();
  if (!mk.IsDone()) {
    return fail(2, 0, "MakeBox not done");
  }
  return okToken(sess->add(mk.Shape()));
}

OpOut occMakeCylinder(uint64_t s, double radius, double height, double /*tol*/) {
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    return fail(5, 0, "invalid session id");
  }
  if (!(radius > 0.0 && height > 0.0)) {
    return fail(3, 0, "cylinder has a non-positive radius or height");
  }
  gp_Ax2 axis;  // default: origin, +Z axis.
  BRepPrimAPI_MakeCylinder mk(axis, radius, height);
  mk.Build();
  if (!mk.IsDone()) {
    return fail(2, 0, "MakeCylinder not done");
  }
  return okToken(sess->add(mk.Shape()));
}

OpOut occMakeSphere(uint64_t s, double radius, double /*tol*/) {
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    return fail(5, 0, "invalid session id");
  }
  if (!(radius > 0.0)) {
    return fail(3, 0, "sphere has a non-positive radius");
  }
  BRepPrimAPI_MakeSphere mk(gp_Pnt(0.0, 0.0, 0.0), radius);
  mk.Build();
  if (!mk.IsDone()) {
    return fail(2, 0, "MakeSphere not done");
  }
  return okToken(sess->add(mk.Shape()));
}

// --- booleans ---------------------------------------------------------------------

OpOut occBoolean(uint64_t s, int32_t op, uint64_t a, uint64_t b, double tol) {
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    return fail(5, 0, "invalid session id");
  }
  if (op < 0 || op > 2) {
    return fail(1, 0, "unknown boolean operation code");
  }
  TopoDS_Shape sa, sb;
  if (!sess->get(a, sa) || !sess->get(b, sb)) {
    return fail(5, 0, "missing operand shape (token not in session)");
  }
  if (isEmptyOfFaces(sa) || isEmptyOfFaces(sb)) {
    return fail(1, 0, "boolean operand is an empty shape");
  }

  // Builder pattern: `sa` is the base argument, `sb` the tool. Both the
  // arguments list AND the tools list must be set or the operation reports
  // IsDone()=false (observed on OCCT 8.0.1 with the appointer-style default).
  NCollection_List<TopoDS_Shape> argList;
  argList.Append(sa);
  NCollection_List<TopoDS_Shape> toolList;
  toolList.Append(sb);

  TopoDS_Shape result;
  if (op == 0) {
    BRepAlgoAPI_Fuse algo;
    algo.SetFuzzyValue(tol);
    algo.SetArguments(argList);
    algo.SetTools(toolList);
    algo.Build();
    if (!algo.IsDone()) {
      return fail(2, 0, "boolean union not done");
    }
    result = algo.Shape();
  } else if (op == 1) {
    BRepAlgoAPI_Cut algo;
    algo.SetFuzzyValue(tol);
    algo.SetArguments(argList);
    algo.SetTools(toolList);
    algo.Build();
    if (!algo.IsDone()) {
      return fail(2, 0, "boolean difference not done");
    }
    result = algo.Shape();
  } else {
    BRepAlgoAPI_Common algo;
    algo.SetFuzzyValue(tol);
    algo.SetArguments(argList);
    algo.SetTools(toolList);
    algo.Build();
    if (!algo.IsDone()) {
      return fail(2, 0, "boolean intersection not done");
    }
    result = algo.Shape();
  }

  if (isEmptyOfFaces(result)) {
    return fail(4, 0, "boolean produced an empty result (no faces)");
  }
  return okToken(sess->add(result));
}

// --- fillet / chamfer -----------------------------------------------------------------

OpOut occFilletChamfer(uint64_t s, int32_t mode, uint64_t subject,
                       rust::Vec<uint64_t> edges, double amount, double /*tol*/) {
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    return fail(5, 0, "invalid session id");
  }
  if (mode != 0 && mode != 1) {
    return fail(1, 0, "unknown fillet/chamfer mode");
  }
  if (!(amount > 0.0)) {
    return fail(3, 0, "fillet/chamfer amount must be positive");
  }
  if (edges.empty()) {
    return fail(1, 0, "no edges selected");
  }
  TopoDS_Shape base;
  if (!sess->get(subject, base)) {
    return fail(5, 0, "missing subject shape");
  }
  if (base.ShapeType() != TopAbs_SOLID) {
    return fail(1, 0, "fillet/chamfer subject is not a solid");
  }

  TopoDS_Shape result;
  if (mode == 0) {
    BRepFilletAPI_MakeFillet mk(base);
    for (uint64_t idx : edges) {
      TopoDS_Edge edge;
      if (!edgeByIndex(base, idx, edge)) {
        return fail(1, 0, "edge index out of range on subject");
      }
      mk.Add(amount, edge);
    }
    mk.Build();
    if (!mk.IsDone()) {
      return fail(2, 0, "fillet not done");
    }
    result = mk.Shape();
  } else {
    BRepFilletAPI_MakeChamfer mk(base);
    for (uint64_t idx : edges) {
      TopoDS_Edge edge;
      if (!edgeByIndex(base, idx, edge)) {
        return fail(1, 0, "edge index out of range on subject");
      }
      mk.Add(amount, edge);
    }
    mk.Build();
    if (!mk.IsDone()) {
      return fail(2, 0, "chamfer not done");
    }
    result = mk.Shape();
  }

  if (isEmptyOfFaces(result)) {
    return fail(4, 0, "fillet/chamfer produced an empty result");
  }
  return okToken(sess->add(result));
}

EdgesOut occEdges(uint64_t s, uint64_t subject) {
  EdgesOut out;
  out.ok = true;
  out.code = 0;
  out.message = rust::String();
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    out.ok = false;
    out.code = 5;
    out.message = rust::String("invalid session id");
    return out;
  }
  TopoDS_Shape shape;
  if (!sess->get(subject, shape)) {
    out.ok = false;
    out.code = 5;
    out.message = rust::String("missing shape");
    return out;
  }
  if (shape.IsNull()) {
    out.ok = false;
    out.code = 1;
    out.message = rust::String("null shape");
    return out;
  }
  uint64_t i = 0;
  for (TopExp_Explorer exp(shape, TopAbs_EDGE); exp.More(); exp.Next(), ++i) {
    out.edges.push_back(i);
  }
  return out;
}

// --- measured properties --------------------------------------------------------------

InfoOut occInfo(uint64_t s, uint64_t token) {
  InfoOut out;
  out.ok = true;
  out.code = 0;
  out.volume = 0.0;
  out.area = 0.0;
  out.nfaces = 0;
  out.nedges = 0;
  out.nverts = 0;
  out.message = rust::String();
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    out.ok = false;
    out.code = 5;
    out.message = rust::String("invalid session id");
    return out;
  }
  TopoDS_Shape shape;
  if (!sess->get(token, shape) || shape.IsNull()) {
    out.ok = false;
    out.code = 5;
    out.message = rust::String("missing shape");
    return out;
  }
  GProp_GProps volumeProps;
  BRepGProp::VolumeProperties(shape, volumeProps);
  GProp_GProps areaProps;
  BRepGProp::SurfaceProperties(shape, areaProps);
  out.volume = volumeProps.Mass();
  out.area = areaProps.Mass();
  out.nfaces = countType(shape, TopAbs_FACE);
  out.nedges = countType(shape, TopAbs_EDGE);
  out.nverts = countType(shape, TopAbs_VERTEX);
  return out;
}

uint64_t occCountShapes(uint64_t s) {
  std::shared_ptr<OepSession> sess = sessionFor(s);
  if (!sess) {
    return 0;
  }
  return sess->count();
}

