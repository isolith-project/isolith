// --- session registry (owned here, guarded by a mutex) ----------------------

std::mutex g_mutex;
std::map<uint64_t, std::shared_ptr<OepSession>> g_sessions;
std::atomic<uint64_t> g_next_session(1);

std::shared_ptr<OepSession> sessionFor(uint64_t id) {
  std::lock_guard<std::mutex> lock(g_mutex);
  std::map<uint64_t, std::shared_ptr<OepSession>>::const_iterator it =
      g_sessions.find(id);
  if (it == g_sessions.end()) {
    return std::shared_ptr<OepSession>();
  }
  return it->second;
}

// --- status helpers ----------------------------------------------------------

OpOut fail(int32_t code, uint64_t token, const std::string& msg) {
  OpOut out;
  out.ok = false;
  out.code = code;
  out.token = token;
  out.message = rust::String(msg);
  return out;
}

OpOut okToken(uint64_t token) {
  OpOut out;
  out.ok = true;
  out.code = 0;
  out.token = token;
  out.message = rust::String();
  return out;
}

uint64_t countType(const TopoDS_Shape& shape, TopAbs_ShapeEnum kind) {
  uint64_t n = 0;
  for (TopExp_Explorer exp(shape, kind); exp.More(); exp.Next()) {
    ++n;
  }
  return n;
}

bool isEmptyOfFaces(const TopoDS_Shape& shape) {
  return shape.IsNull() || countType(shape, TopAbs_FACE) == 0;
}

bool edgeByIndex(const TopoDS_Shape& shape, uint64_t index, TopoDS_Edge& out) {
  if (shape.IsNull()) {
    return false;
  }
  uint64_t i = 0;
  for (TopExp_Explorer exp(shape, TopAbs_EDGE); exp.More(); exp.Next(), ++i) {
    if (i == index) {
      out = TopoDS::Edge(exp.Current());
      return true;
    }
  }
  return false;
}

// Build a planar face from an explicit 3D point loop; the loop closes
// implicitly back to the first point. Returns false on degenerate input
// (fewer than 3 points, builder failure), so sweep failures surface as typed
// errors, never a panic.
bool makeWireFace(const std::vector<gp_Pnt>& pts, TopoDS_Face& out) {
  if (pts.size() < 3) {
    return false;
  }
  BRepBuilderAPI_MakeWire wire;
  for (size_t i = 0; i < pts.size(); ++i) {
    const gp_Pnt& a = pts[i];
    const gp_Pnt& b = pts[(i + 1) % pts.size()];
    BRepBuilderAPI_MakeEdge me(a, b);
    if (!me.IsDone()) {
      return false;
    }
    wire.Add(me.Edge());
  }
  if (!wire.IsDone()) {
    return false;
  }
  BRepBuilderAPI_MakeFace face(wire.Wire(), true);
  if (!face.IsDone()) {
    return false;
  }
  out = face.Face();
  return true;
}

// Build the extrude profile face: the planar Z=0 face of the point loop
// `xy[0],xy[1],...` (each pair is x,y), so the sweep runs along +Z.
bool makeExtrudeFace(const rust::Vec<double>& xy, TopoDS_Face& out) {
  const size_t n = xy.size() / 2;
  if (n < 3) {
    return false;
  }
  std::vector<gp_Pnt> pts;
  pts.reserve(n);
  for (size_t i = 0; i < n; ++i) {
    const double x = xy[2 * i];
    const double y = xy[2 * i + 1];
    if (!std::isfinite(x) || !std::isfinite(y)) {
      return false;
    }
    pts.emplace_back(x, y, 0.0);
  }
  return makeWireFace(pts, out);
}

// Build the revolve profile face: a meridian cross-section face in the XZ
// half-plane. Each profile pair is (radial distance from the Z axis, axial
// height); the sweep rotates about the Z axis.
bool makeRevolveFace(const rust::Vec<double>& rz, TopoDS_Face& out) {
  const size_t n = rz.size() / 2;
  if (n < 3) {
    return false;
  }
  std::vector<gp_Pnt> pts;
  pts.reserve(n);
  for (size_t i = 0; i < n; ++i) {
    const double r = rz[2 * i];
    const double z = rz[2 * i + 1];
    if (!std::isfinite(r) || !std::isfinite(z) || r < 0.0) {
      return false;
    }
    pts.emplace_back(r, 0.0, z);
  }
  return makeWireFace(pts, out);
}

