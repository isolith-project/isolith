#!/usr/bin/env python3
"""Generate docs/ROADMAP.md from docs/scope-register.json (community intake,
item 6).

The public ROADMAP is a machine rendering of the scope register, never a
hand-written wish list: every roadmap line traces to a register row or a
policy field in the JSON, and a row's status may not exceed what a green
accepted test proves (the register's honesty rule, enforced by
python/oep_tooling/scope_register_check.py and tests/test_scope_register.py).
If the register changes, re-run this script (the output is committed).

Usage:
    python3 scripts/generate-roadmap.py            # write docs/ROADMAP.md
    python3 scripts/generate-roadmap.py --dry-run  # print to stdout

Stdlib only, deterministic output: same input, same bytes. No em dashes
(U+2014) are emitted.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTER = os.path.join(REPO_ROOT, "docs", "scope-register.json")
OUT = os.path.join(REPO_ROOT, "docs", "ROADMAP.md")

STATE_LABELS = {
    "not-scoped": "Name in the parity baseline, no commitment to build it yet.",
    "planned": "Committed to scope, sequenced, an owner named (evidence: decision/ADR/card).",
    "building": "Actively built (evidence: at least one green accepted test on main).",
    "shippable": "Engineers can do the main job end to end (evidence: green accepted test on real material).",
}


def wrap_line(text: str, width: int = 78) -> list[str]:
    """Word-wrap one paragraph line without breaking tokens; no em dashes."""
    words = text.split()
    if not words:
        return [""]
    lines, cur = [], ""
    for w in words:
        if not cur:
            cur = w
        elif len(cur) + 1 + len(w) <= width:
            cur += " " + w
        else:
            lines.append(cur)
            cur = w
    lines.append(cur)
    return lines


def render(register: dict) -> str:
    policy = register.get("policy", {})
    order = register.get("commitment_order", {})
    rows = register.get("rows", [])
    updated = register.get("updated", "unknown")
    out: list[str] = []
    out.append("---")
    out.append("title: \"Isolith Public ROADMAP\"")
    out.append("version: 1.0.0")
    out.append("date: 2026-10-27")
    out.append("status: Generated")
    out.append("source: docs/scope-register.json")
    out.append("generator: scripts/generate-roadmap.py")
    out.append("---")
    out.append("")
    out.append("# Isolith Public ROADMAP")
    out.append("")
    out.append("This page is a machine rendering of the scope register")
    out.append("(`docs/scope-register.json`, updated %s). It is generated by" % updated)
    out.append("`scripts/generate-roadmap.py` from that file and is never edited")
    out.append("by hand. Every line below traces to a register row or a policy")
    out.append("field; nothing here is a wish list.")
    out.append("")
    out.append("## Product bar")
    out.append("")
    for line in wrap_line(policy.get("product_bar", "")):
        out.append(line)
    out.append("")
    hrule = policy.get("honesty_rule", "")
    out.append("**Honesty rule (from the register):** %s." % hrule)
    out.append("Enforced by `python/oep_tooling/scope_register_check.py` and")
    out.append("`tests/test_scope_register.py`; a row's status may not exceed")
    out.append("what a green accepted test proves.")
    out.append("")
    out.append("## Status tokens")
    out.append("")
    out.append("| Token | Meaning |")
    out.append("|---|---|")
    rank = policy.get("status_rank", [])
    for token in rank:
        out.append("| `%s` | %s |" % (token, STATE_LABELS.get(token, "")))
    out.append("")
    out.append("## What commits first")
    out.append("")
    out.extend(wrap_line("Near term: " + ", ".join(order.get("near_term", [])) + "."))
    out.append("")
    for line in wrap_line("Spine: " + order.get("spine", "")):
        out.append(line)
    out.append("")
    for line in wrap_line(
            "Kernel seam: " + ", ".join(order.get("after_kernel_seam", [])) + "."):
        out.append(line)
    for line in wrap_line(order.get("after_kernel_seam_note", "")):
        out.append(line)
    out.append("")
    for line in wrap_line("Secondary (2027.2+): "
                          + ", ".join(order.get("secondary", [])) + "."):
        out.append(line)
    for line in wrap_line(order.get("secondary_note", "")):
        out.append(line)
    out.append("")
    for line in wrap_line("Class-A program: "
                          + ", ".join(order.get("class_a_program", [])) + "."):
        out.append(line)
    for line in wrap_line(order.get("class_a_program_note", "")):
        out.append(line)
    out.append("")
    for line in wrap_line("Composites: " + order.get("composites_note", "")):
        out.append(line)
    out.append("")
    out.append("## Capability register (from `rows`)")
    out.append("")
    out.append("| Row | Capability | Status | Cost class | Workstream | CATIA | SolidWorks | Evidence |")
    out.append("|---|---|---|---|---|---|---|---|")
    for row in rows:
        ev = row.get("evidence", {})
        if ev.get("kind") == "decision":
            evtxt = "decision: " + ev.get("ref", "")
        elif ev.get("kind") == "test":
            evtxt = "test: " + ev.get("ref", "")
        else:
            evtxt = (ev.get("kind", "") + ": " + ev.get("ref", "")).strip(": ")
        out.append("| `%s` | %s | %s | %s | %s | %s | %s | %s |"
                   % (row.get("id", ""), row.get("capability", ""),
                      row.get("status", ""), row.get("cost_class", ""),
                      row.get("workstream", ""), row.get("catia", ""),
                      row.get("solidworks", ""), evtxt))
    out.append("")
    out.append("## How to read this")
    out.append("")
    out.append("- The register is the commitment surface. A capability that is")
    out.append("  absent is a decision, not an accident (`not-scoped` exists to")
    out.append("  keep it visible).")
    out.append("- Status moves only `not-scoped -> planned -> building ->")
    out.append("  shippable`, and only while a green accepted test proves the")
    out.append("  new claim (the register's upgrade rule, decision #19).")
    out.append("- Vendor cells are reference only: how CATIA and SolidWorks")
    out.append("  ship the capability today. They are not commitments.")
    out.append("- Regenerate this page with: `python3 scripts/generate-roadmap.py`")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate docs/ROADMAP.md from docs/scope-register.json.")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the road map to stdout instead of writing")
    args = parser.parse_args(argv)
    with open(REGISTER, encoding="utf-8") as fh:
        register = json.load(fh)
    text = render(register)
    if "\u2014" in text:
        sys.stderr.write("roadmap generator refuses to emit an em dash\n")
        return 2
    if args.dry_run:
        sys.stdout.write(text)
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d bytes, from %s)"
          % (OUT, os.path.getsize(OUT), REGISTER))
    return 0


if __name__ == "__main__":
    sys.exit(main())
