#!/usr/bin/env python3
"""Acceptance test for Keelworks P6-M5-T03: 1M-triangle scene interactive on
U1-class hardware, measured budget.

Written FIRST (TDD). The committed performance benchmark at P6-M5/perf/1m-scene
and its measured report must make this test pass. It verifies the real
material, not mocks:

  benchmark  => a standalone wgpu benchmark crate exists (P6-M5/perf/1m-scene)
                and is deliberately NOT a root workspace member (CI has no GPU,
                same headless test gate shape as the P6-M5-T01 spike)
  scene      => the benchmark generates a REAL >= 1,000,000-triangle indexed
                mesh (deterministic grid), uploaded to the GPU
  headless   => wgpu + WGSL, no surface/swapchain API anywhere in the source
  measure    => the benchmark times per-frame rendering over N measured frames
                after a warmup, reporting min/mean/p95/max frame time and mean
                FPS, computed from a real headless wgpu run on the reference
                host (U1)
  budget     => the measured numbers meet the INTERACTIVE budget: mean frame
                time <= 33.33 ms (>= 30 FPS floor) with p95 <= 50 ms, recorded
                as the measured budget in a committed report JSON + a versioned
                writeup (P6-M5/viewer-perf-1m-budget.md)
  proof      => a committed frame proof PNG shows the mesh actually rendered
                headless on U1, and the report cites the real adapter/driver
  provenance => the report is generated by the committed benchmark binary on
                real hardware, not synthetic static numbers

Plus the program surface-language rule (no em dashes, no curly quotes) on the
files this card adds, and the P6-M5-T01 headless test gate (proof + report are
committed so the GPU-less CI container can verify the gate).

Run:  python3 tests/test_viewer_perf_1m_acceptance.py   (and under pytest)
Exit 0 = pass; nonzero = fail. Stdlib only.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BENCH_DIR = os.path.join(ROOT, "P6-M5", "perf", "1m-scene")
BENCH_CARGO = os.path.join(BENCH_DIR, "Cargo.toml")
BENCH_SRC = os.path.join(BENCH_DIR, "src", "main.rs")
REPORT_JSON = os.path.join(BENCH_DIR, "report-1m-triangles.json")
PROOF_PNG = os.path.join(BENCH_DIR, "frame-proof.png")
BUDGET_MD = os.path.join(ROOT, "P6-M5", "viewer-perf-1m-budget.md")
ROOT_CARGO = os.path.join(ROOT, "Cargo.toml")
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
EM_DASH = "\u2014"  # U+2014, the em dash the program bans from its prose

# The interactive budget recorded by this card (measured on real hardware).
# "Interactive" for a viewer means the sustained frame cadence stays above the
# 30 FPS floor with reasonable headroom; see viewer-perf-1m-budget.md.
BUDGET_MEAN_FRAME_MS = 33.33   # 1000/30 FPS floor
BUDGET_P95_FRAME_MS = 50.0     # p95 budget: occasional spikes allowed, bounded
MIN_TRIANGLES = 1_000_000
MIN_MEASURED_FRAMES = 30
MIN_FPS_FLOOR = 30.0

failures = []


def check(cond, msg):
    if not cond:
        failures.append(msg)


def read_text(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def png_ok(path):
    if not os.path.isfile(path):
        return False, "missing"
    with open(path, "rb") as fh:
        head = fh.read(8)
    if head != PNG_MAGIC:
        return False, "bad magic"
    if os.path.getsize(path) < 10_000:
        return False, "implausibly small (%d bytes)" % os.path.getsize(path)
    return True, "ok"


def run_checks():
    print("P6-M5-T03 viewer performance (1M triangles, measured budget)")
    print("bench: %s" % BENCH_DIR)
    print("budget: mean <= %.2f ms, p95 <= %.1f ms, triangles >= %d" % (
        BUDGET_MEAN_FRAME_MS, BUDGET_P95_FRAME_MS, MIN_TRIANGLES))
    print("=" * 66)

    # 1. The benchmark crate exists and is a standalone (non-workspace) crate.
    check(os.path.isfile(BENCH_CARGO), "missing: P6-M5/perf/1m-scene/Cargo.toml")
    check(os.path.isfile(BENCH_SRC), "missing: P6-M5/perf/1m-scene/src/main.rs")
    if os.path.isfile(BENCH_CARGO):
        bc = read_text(BENCH_CARGO)
        check("wgpu" in bc, "benchmark must depend on wgpu")
        check("[workspace]" in bc,
              "benchmark crate must declare its own [workspace] (standalone, "
              "CI has no GPU; same shape as the P6-M5-T01 spike)")
    # It must NOT be a root workspace member (GPU-less CI would try to build).
    if os.path.isfile(ROOT_CARGO):
        rc = read_text(ROOT_CARGO)
        check("1m-scene" not in rc,
              "benchmark must NOT be a root workspace member (CPU-less CI)")

    # 2. Scene generation: a real >= 1M triangle indexed mesh.
    if os.path.isfile(BENCH_SRC):
        src = read_text(BENCH_SRC)
        slow = src.lower()
        check("wgpu" in slow, "benchmark source must use wgpu")
        check("wgsl" in slow or "shader" in slow,
              "benchmark source must contain a WGSL shader")
        # No surface/swapchain API anywhere: pure headless render.
        check("create_surface(" not in slow and "surface_configuration" not in slow
              and "get_current_texture" not in slow and "swapchain_descriptor" not in slow,
              "benchmark must not use any surface/swapchain API (headless proof; "
              "prose mentions like 'no swapchain' in comments are fine)")
        # The mesh must be indexed with >= 1M triangles; the source states the
        # generated triangle count (deterministic grid math) and a literal
        # target marker so the count is auditable without executing code.
        check("triangles" in src or "triangle_count" in src or "indices" in src,
              "source must build an indexed triangle mesh")
        check("1_000_000" in src or "1000000" in src,
              "source must state the >= 1M triangle target (deterministic grid)")

    # 3. Measured report exists, is valid JSON, and records real numbers.
    check(os.path.isfile(REPORT_JSON), "missing measured report: report-1m-triangles.json")
    report = {}
    if os.path.isfile(REPORT_JSON):
        try:
            with open(REPORT_JSON, encoding="utf-8") as fh:
                report = json.load(fh)
        except ValueError as e:
            check(False, "report JSON does not parse: %s" % e)

    def rep(key, default=None):
        return report.get(key, default)

    tri = rep("triangles")
    check(isinstance(tri, (int, float)) and tri >= MIN_TRIANGLES,
          "report must record triangles >= %d, got %r" % (MIN_TRIANGLES, tri))

    frames = rep("measured_frames")
    check(isinstance(frames, int) and frames >= MIN_MEASURED_FRAMES,
          "report must record >= %d measured frames, got %r" % (MIN_MEASURED_FRAMES, frames))

    mean_ms = rep("mean_frame_ms")
    check(isinstance(mean_ms, (int, float)) and mean_ms > 0
          and mean_ms <= BUDGET_MEAN_FRAME_MS,
          "report mean frame time %.4f ms must be > 0 and <= %.2f ms" % (
              mean_ms if isinstance(mean_ms, (int, float)) else -1,
              BUDGET_MEAN_FRAME_MS))

    p95_ms = rep("p95_frame_ms")
    check(isinstance(p95_ms, (int, float)) and p95_ms > 0
          and p95_ms <= BUDGET_P95_FRAME_MS,
          "report p95 frame time %.4f ms must be > 0 and <= %.1f ms" % (
              p95_ms if isinstance(p95_ms, (int, float)) else -1,
              BUDGET_P95_FRAME_MS))

    fps = rep("fps_mean")
    if isinstance(fps, (int, float)):
        eff_fps = fps
    elif isinstance(mean_ms, (int, float)) and mean_ms > 0:
        eff_fps = 1000.0 / mean_ms
    else:
        eff_fps = 0.0
    check(eff_fps >= MIN_FPS_FLOOR,
          "effective FPS %.2f must be >= %.1f (interactive floor)" % (eff_fps, MIN_FPS_FLOOR))

    # 4. Provenance: report cites the real adapter/driver it was measured on.
    check(bool(rep("adapter")), "report must record the GPU adapter name")
    check(bool(rep("driver")), "report must record the driver version")
    check(bool(rep("backend")), "report must record the backend (Vulkan)")
    check(bool(rep("host")), "report must record the host identifier")

    # 5. Committed frame proof: a real headless render on the reference host.
    pngst, why = png_ok(PROOF_PNG)
    check(pngst, "proof frame %s (%s)" % ("not valid PNG" if not pngst else "ok", why))

    # 6. Versioned writeup with the recorded budget and ADR cross-reference.
    check(os.path.isfile(BUDGET_MD), "missing writeup: P6-M5/viewer-perf-1m-budget.md")
    if os.path.isfile(BUDGET_MD):
        md = read_text(BUDGET_MD)
        mdl = md.lower()
        check("P6-M5-T03" in md, "writeup must cite its own card P6-M5-T03")
        check("1_000_000" in md or "1M" in md or "one million" in mdl,
              "writeup must state the 1M-triangle scene target")
        check("budget" in mdl, "writeup must name the interactive budget")
        check("adapter" in mdl or "driver" in mdl or "gb10" in mdl or "nvidia" in mdl,
              "writeup must cite the measured host/adapter (real material)")
        check("P6-M5-T01" in md or "renderer-backend-wgpu-adr" in md,
              "writeup must cross-reference the renderer backend decision")

    # 7. Surface-language rule on the files this card adds.
    for path, label in ((BENCH_SRC, "benchmark main.rs"),
                        (BUDGET_MD, "budget writeup")):
        if os.path.isfile(path):
            text = read_text(path)
            check(EM_DASH not in text,
                  "%s must not contain em dashes (program discipline)" % label)
            ncurly = (text.count("\u201c") + text.count("\u201d")
                      + text.count("\u2018") + text.count("\u2019"))
            check(ncurly == 0,
                  "%s must not contain curly quotes; plain ASCII quotes only" % label)

    return failures


def main():
    failures = run_checks()
    if failures:
        print("VIEWER PERFORMANCE 1M-triangle ACCEPTANCE FAILED (%d)" % len(failures))
        for f in failures:
            print("  -", f)
        sys.exit(1)
    print("VIEWER PERFORMANCE 1M-triangle ACCEPTANCE PASSED: benchmark renders "
          "a >= 1M-triangle scene headless on U1 and sustains the interactive "
          "budget (mean <= %.2f ms, p95 <= %.1f ms); report + proof committed."
          % (BUDGET_MEAN_FRAME_MS, BUDGET_P95_FRAME_MS))
    return 0


def test_viewer_perf_1m_acceptance():
    """pytest entry point: the same checks, asserted without sys.exit."""
    failures = run_checks()
    assert not failures, "viewer perf 1M-triangle acceptance failed (%d): %s" % (
        len(failures), failures[:5])


if __name__ == "__main__":
    main()
